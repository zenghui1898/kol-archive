export type Hexagram = {
  id: number;
  name: string;
  upper: TrigramKey;
  lower: TrigramKey;
  gist: string;
  judgment: string;
  image: string;
  lines: readonly [string, string, string, string, string, string];
  title: string;
  bits: string;
  character: string;
  upperLabel: string;
  lowerLabel: string;
};

function titleOf(name: string, upper: TrigramKey, lower: TrigramKey): string {
  const above = TRIGRAMS[upper];
  const below = TRIGRAMS[lower];
  if (upper === lower) return `${name}为${above.nature}`;
  return `${above.nature}${below.nature}${name}`;
}

function bitsOf(upper: TrigramKey, lower: TrigramKey): string {
  return [...TRIGRAMS[lower].lines, ...TRIGRAMS[upper].lines].join("");
}

function labelOf(key: TrigramKey): string {
  const trigram = TRIGRAMS[key];
  return `${trigram.name}为${trigram.nature}`;
}

export const HEXAGRAMS: Hexagram[] = SEEDS.map((seed, index) => ({
  ...seed,
  id: index + 1,
  title: titleOf(seed.name, seed.upper, seed.lower),
  bits: bitsOf(seed.upper, seed.lower),
  character: String.fromCodePoint(0x4dc0 + index),
  upperLabel: labelOf(seed.upper),
  lowerLabel: labelOf(seed.lower),
}));

const pairs = new Set(HEXAGRAMS.map((hex) => `${hex.upper}:${hex.lower}`));
const patterns = new Set(HEXAGRAMS.map((hex) => hex.bits));
if (HEXAGRAMS.length !== 64 || pairs.size !== 64 || patterns.size !== 64) {
  throw new Error("六十四卦数据不完整");
}

const byBits = new Map(HEXAGRAMS.map((hex) => [hex.bits, hex]));

export function hexagramById(id: number): Hexagram | undefined {
  if (!Number.isInteger(id) || id < 1 || id > 64) return undefined;
  return HEXAGRAMS[id - 1];
}

export function hexagramByBits(bits: string): Hexagram {
  const found = byBits.get(bits);
  if (!found) throw new Error(`未知卦象 ${bits}`);
  return found;
}
